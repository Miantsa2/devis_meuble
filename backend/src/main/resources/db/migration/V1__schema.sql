CREATE TABLE app_user (
  id BIGSERIAL PRIMARY KEY, username VARCHAR(100) NOT NULL UNIQUE,
  password_hash VARCHAR(100) NOT NULL, role VARCHAR(20) NOT NULL);

CREATE TABLE furniture_type (id VARCHAR(50) PRIMARY KEY, label VARCHAR(200) NOT NULL);

CREATE TABLE panel_material (
  id BIGSERIAL PRIMARY KEY, code VARCHAR(50) NOT NULL UNIQUE, name VARCHAR(200) NOT NULL, family VARCHAR(50),
  thickness_mm DOUBLE PRECISION NOT NULL, length_mm DOUBLE PRECISION NOT NULL, width_mm DOUBLE PRECISION NOT NULL,
  price_per_sheet NUMERIC(14,2) NOT NULL DEFAULT 0, grain BOOLEAN NOT NULL DEFAULT FALSE,
  density_kg_m3 DOUBLE PRECISION, young_modulus_mpa DOUBLE PRECISION, active BOOLEAN NOT NULL DEFAULT TRUE);

CREATE TABLE edge_band (
  id BIGSERIAL PRIMARY KEY, code VARCHAR(50) NOT NULL UNIQUE, name VARCHAR(200) NOT NULL,
  thickness_mm DOUBLE PRECISION NOT NULL, width_mm DOUBLE PRECISION NOT NULL DEFAULT 0,
  price_per_meter NUMERIC(14,4) NOT NULL DEFAULT 0, active BOOLEAN NOT NULL DEFAULT TRUE);

CREATE TABLE hardware_item (
  id BIGSERIAL PRIMARY KEY, code VARCHAR(50) NOT NULL UNIQUE, name VARCHAR(200) NOT NULL, category VARCHAR(50),
  unit_price NUMERIC(14,4) NOT NULL DEFAULT 0, slide_length_mm DOUBLE PRECISION, active BOOLEAN NOT NULL DEFAULT TRUE);

CREATE TABLE manufacturing_rule (
  id BIGSERIAL PRIMARY KEY, furniture_type VARCHAR(50) NOT NULL REFERENCES furniture_type(id) ON UPDATE CASCADE,
  rule_key VARCHAR(100) NOT NULL, value NUMERIC(18,6) NOT NULL, unit VARCHAR(30),
  source VARCHAR(1000), validation_status VARCHAR(20) NOT NULL DEFAULT 'TO_VALIDATE', description VARCHAR(1000),
  UNIQUE (furniture_type, rule_key));

CREATE TABLE labor_operation (
  id BIGSERIAL PRIMARY KEY, furniture_type VARCHAR(50) NOT NULL REFERENCES furniture_type(id) ON UPDATE CASCADE,
  code VARCHAR(50) NOT NULL, label VARCHAR(200) NOT NULL, basis VARCHAR(30) NOT NULL,
  minutes NUMERIC(12,4) NOT NULL DEFAULT 0, validation_status VARCHAR(20) NOT NULL DEFAULT 'TO_VALIDATE',
  UNIQUE (furniture_type, code));

CREATE TABLE threshold_rule (
  id BIGSERIAL PRIMARY KEY, kind VARCHAR(30) NOT NULL, up_to DOUBLE PRECISION NOT NULL, count INT NOT NULL,
  source VARCHAR(1000), validation_status VARCHAR(20) NOT NULL DEFAULT 'TO_VALIDATE');

CREATE TABLE app_setting (
  id VARCHAR(100) PRIMARY KEY, value_numeric NUMERIC(18,6), value_text VARCHAR(100),
  unit VARCHAR(30), description VARCHAR(1000));

CREATE TABLE tax_rate (
  id BIGSERIAL PRIMARY KEY, code VARCHAR(30) NOT NULL UNIQUE, label VARCHAR(100) NOT NULL,
  rate_percent NUMERIC(8,4) NOT NULL DEFAULT 0, active BOOLEAN NOT NULL DEFAULT TRUE);

CREATE TABLE quote (
  id BIGSERIAL PRIMARY KEY, reference VARCHAR(30), customer_name VARCHAR(200), customer_contact VARCHAR(200),
  created_at TIMESTAMPTZ NOT NULL, created_by VARCHAR(100), input_json TEXT NOT NULL, result_json TEXT NOT NULL,
  total_ht NUMERIC(14,2), total_ttc NUMERIC(14,2), currency VARCHAR(10));
